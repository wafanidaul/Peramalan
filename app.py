def hitung_tahun_bulan(periode: int):
    # Periode 1 = Maret 2024 (index bulan = 2 dari 0-based)
    total_bulan = (2024 * 12 + 2) + (periode - 1)
    tahun = total_bulan // 12
    bulan = NAMA_BULAN[total_bulan % 12]
    return tahun, bulan


